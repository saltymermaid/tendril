"""OAuth discovery metadata for the MCP connector (RFC 8414 / RFC 9728).

Hand-written rather than generated by the `mcp` SDK: the SDK's own metadata routes are
registered *inside* the Streamable HTTP sub-app it builds, so if that app is mounted
under a path prefix (as ours is, at /api/mcp/rpc) those routes end up nested under the
prefix too — breaking the RFC 8615 requirement that `.well-known/*` live at the true
origin root. These two routes are registered directly on the root FastAPI app instead.
"""

from fastapi import APIRouter, Request

from app.config import get_settings

settings = get_settings()
router = APIRouter(tags=["mcp-wellknown"])


def _base_url(request: Request) -> str:
    if settings.base_url:
        return settings.base_url.rstrip("/")
    return str(request.base_url).rstrip("/")


@router.get("/.well-known/oauth-authorization-server")
async def oauth_authorization_server_metadata(request: Request):
    base = _base_url(request)
    return {
        "issuer": base,
        "authorization_endpoint": f"{base}/api/mcp/authorize",
        "token_endpoint": f"{base}/api/mcp/token",
        "response_types_supported": ["code"],
        "grant_types_supported": ["authorization_code", "refresh_token"],
        "token_endpoint_auth_methods_supported": ["client_secret_post"],
        "code_challenge_methods_supported": ["S256"],
    }


@router.get("/.well-known/oauth-protected-resource/api/mcp/rpc")
async def oauth_protected_resource_metadata(request: Request):
    base = _base_url(request)
    return {
        "resource": f"{base}/api/mcp/rpc",
        "authorization_servers": [base],
        "scopes_supported": ["read", "write"],
        "bearer_methods_supported": ["header"],
    }
